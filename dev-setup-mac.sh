#!/usr/bin/env bash
# =============================================================================
# IDMC Vendor Portal — Local Dev Setup  (macOS)
# =============================================================================
# Targets:  macOS 13+ (Intel or Apple Silicon), Python 3.9+, Node 20 LTS
# Database: SQLite (no external DB needed for local dev)
# Portal:   Vite dev server (no nginx needed)
# Run once, then use the three start commands printed at the end.
# Safe to re-run — skips steps that are already complete.
# =============================================================================
set -euo pipefail

# ── Colour helpers ────────────────────────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; RESET='\033[0m'

info()   { echo -e "${CYAN}[INFO]${RESET}  $*"; }
ok()     { echo -e "${GREEN}[ OK ]${RESET}  $*"; }
warn()   { echo -e "${YELLOW}[WARN]${RESET}  $*"; }
header() { echo -e "\n${BOLD}${CYAN}══ $* ══${RESET}"; }
manual() { echo -e "${YELLOW}[TODO]${RESET}  $*"; }
fatal()  { echo -e "${RED}[FAIL]${RESET}  $*"; exit 1; }

# ── Project root ──────────────────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="$SCRIPT_DIR"

header "IDMC Vendor Portal — macOS Dev Setup"
info "Project root: $PROJECT"

# =============================================================================
# 1. Prerequisite checks
# =============================================================================
header "Checking prerequisites"

# Python 3.9+ (3.12 preferred; 3.9 is the minimum the deps support)
PYTHON=""
for candidate in python3.12 python3.11 python3.10 python3.9 python3 python; do
    if command -v "$candidate" &>/dev/null; then
        ver=$("$candidate" --version 2>&1 | grep -oE '[0-9]+\.[0-9]+' | head -1)
        major=$(echo "$ver" | cut -d. -f1)
        minor=$(echo "$ver" | cut -d. -f2)
        if [[ "$major" -eq 3 && "$minor" -ge 9 ]]; then
            PYTHON="$candidate"
            break
        fi
    fi
done
[[ -z "$PYTHON" ]] && fatal "Python 3.9+ not found. Install with: brew install python@3.12"
PYTHON_VER=$($PYTHON --version 2>&1)
ok "Python: $PYTHON_VER  ($PYTHON)"
[[ "$PYTHON_VER" != *"3.12"* ]] && warn "Python 3.12 is recommended; found $PYTHON_VER. Run 'brew install python@3.12' to upgrade."

# Node 20+
command -v node &>/dev/null || fatal "Node.js not found. Install with: brew install node@20"
NODE_MAJOR=$(node --version | grep -oE '[0-9]+' | head -1)
[[ "$NODE_MAJOR" -lt 20 ]] && fatal "Node.js 20+ required (found $(node --version)). Run: brew install node@20"
ok "Node: $(node --version)  npm: $(npm --version)"

# OpenSSL (for secret generation)
command -v openssl &>/dev/null || fatal "openssl not found. Install with: brew install openssl@3"
ok "OpenSSL: $(openssl version 2>&1 | cut -d' ' -f1-2)"

# =============================================================================
# 2. Create local-data directory tree
# =============================================================================
header "Creating local data directories"

mkdir -p \
    "$PROJECT/local-data/staging/pm_scripts" \
    "$PROJECT/local-data/staging/source_files" \
    "$PROJECT/local-data/staging/target_files" \
    "$PROJECT/local-data/staging/parameter_files" \
    "$PROJECT/local-data/scripts" \
    "$PROJECT/local-data/logs/auth" \
    "$PROJECT/local-data/logs/api" \
    "$PROJECT/local-data/logs/agent"
ok "Staging and log directories ready under $PROJECT/local-data/"

# Write the local log_paths override (points at local-data/, not system dirs)
LOCAL_LOG_PATHS="$PROJECT/local-data/log_paths.local.yaml"
if [[ ! -f "$LOCAL_LOG_PATHS" ]]; then
    cat > "$LOCAL_LOG_PATHS" <<EOF
# Local dev override — generated by dev-setup-mac.sh
# Points to local-data/ instead of production system log directories.
roots:
  - name: staging
    label: "IDMC Staging"
    path: ${PROJECT}/local-data/staging
  - name: auth_logs
    label: "Auth Service Logs"
    path: ${PROJECT}/local-data/logs/auth
  - name: api_logs
    label: "Backend API Logs"
    path: ${PROJECT}/local-data/logs/api
  - name: agent_logs
    label: "IDMC Secure Agent Logs"
    path: ${PROJECT}/local-data/logs/agent
EOF
    ok "Local log_paths written to $LOCAL_LOG_PATHS"
fi

# =============================================================================
# 3. Generate secrets
# =============================================================================
header "Generating secrets"

ENV_FILE="$PROJECT/.env.local"
PEM_DIR="$PROJECT/local-data"
PRIV_PEM="$PEM_DIR/jwt_private.pem"
PUB_PEM="$PEM_DIR/jwt_public.pem"

# Detect stale .env.local that has inline JWT keys (old broken format):
# those values have no PEM headers and won't work with python-jose.
NEEDS_REGEN=false
if [[ -f "$ENV_FILE" ]]; then
    # Check that the PEM files also exist on disk
    if [[ ! -f "$PRIV_PEM" || ! -f "$PUB_PEM" ]]; then
        warn ".env.local exists but PEM key files are missing — regenerating secrets."
        rm -f "$ENV_FILE"
        NEEDS_REGEN=true
    # Check old inline format: value starts directly with base64 (no -----BEGIN header)
    elif grep -q "^JWT_SIGNING_KEY=[A-Za-z0-9+/]" "$ENV_FILE" 2>/dev/null; then
        warn ".env.local has inline JWT keys (old format, missing PEM headers) — regenerating."
        rm -f "$ENV_FILE"
        NEEDS_REGEN=true
    else
        warn ".env.local already exists — skipping secret generation."
        warn "Delete $ENV_FILE and re-run to regenerate all secrets."
    fi
fi

if [[ ! -f "$ENV_FILE" ]]; then
    info "Generating RSA key pair (4096-bit) for JWT signing..."
    # Generate PKCS#1 RSA private key, then convert to PKCS#8
    openssl genrsa 4096 2>/dev/null | \
        openssl pkcs8 -topk8 -nocrypt -out "$PRIV_PEM" 2>/dev/null
    openssl rsa -in "$PRIV_PEM" -pubout -out "$PUB_PEM" 2>/dev/null
    chmod 600 "$PRIV_PEM"
    ok "PEM key files written to $PEM_DIR/"

    # Verify the PEM headers are present before continuing
    grep -q "BEGIN" "$PRIV_PEM" || fatal "Private key PEM generation failed — no BEGIN header."
    grep -q "BEGIN" "$PUB_PEM"  || fatal "Public key PEM generation failed — no BEGIN header."

    ADMIN_API_KEY=$(openssl rand -hex 32)
    ADMIN_SESSION_SECRET=$(openssl rand -hex 32)
    UPLOAD_TOKEN_SECRET=$(openssl rand -hex 32)

    # JWT keys are stored as file paths — the env-loader reads the actual PEM
    # content at runtime so python-jose receives a proper multiline PEM string.
    cat > "$ENV_FILE" <<EOF
# IDMC Vendor Portal — local dev environment
# Generated by dev-setup-mac.sh — do not commit this file

# ── Database (SQLite for local dev) ──────────────────────────────────────────
DB_URL=sqlite+aiosqlite:///./dev.db

# ── JWT key paths (loaded as PEM content by load-env.sh) ─────────────────────
JWT_SIGNING_KEY_FILE=${PRIV_PEM}
JWT_PUBLIC_KEY_FILE=${PUB_PEM}

# ── Auth Service ──────────────────────────────────────────────────────────────
ADMIN_API_KEY=${ADMIN_API_KEY}
ADMIN_SESSION_SECRET=${ADMIN_SESSION_SECRET}
ENROLLMENT_LINK_BASE_URL=http://localhost:5173/enroll

# ── Backend API ───────────────────────────────────────────────────────────────
AUTH_SERVICE_URL=http://127.0.0.1:8001
IDMC_STAGING_ROOT=${PROJECT}/local-data/staging
ALLOWED_PATHS_CONFIG=${PROJECT}/backend-api/config/paths.yaml
OPERATIONS_CONFIG=${PROJECT}/backend-api/config/operations.yaml
LOG_PATHS_CONFIG=${LOCAL_LOG_PATHS}
UPLOAD_TOKEN_SECRET=${UPLOAD_TOKEN_SECRET}
LLM_SETTINGS_PATH=${PROJECT}/local-data/llm-settings.enc

# ── LLM (set your API key here or via Admin Console after first boot) ─────────
LLM_PROVIDER=anthropic
LLM_API_KEY=
LLM_MODEL=claude-opus-4-8
LLM_MAX_CONTEXT_TOKENS=80000
EOF
    ok "Secrets written to $ENV_FILE"
fi

# Load env vars into this shell session.
# JWT_SIGNING_KEY and JWT_PUBLIC_KEY are exported from file content (not stored inline).
set -a
# shellcheck source=/dev/null
source "$ENV_FILE"
set +a
if [[ -f "${JWT_SIGNING_KEY_FILE:-}" ]]; then
    export JWT_SIGNING_KEY
    JWT_SIGNING_KEY=$(cat "$JWT_SIGNING_KEY_FILE")
fi
if [[ -f "${JWT_PUBLIC_KEY_FILE:-}" ]]; then
    export JWT_PUBLIC_KEY
    JWT_PUBLIC_KEY=$(cat "$JWT_PUBLIC_KEY_FILE")
fi

# =============================================================================
# 4. Auth Service — venv + dependencies + migrations + seed admin
# =============================================================================
header "Auth Service — Python environment"

AUTH_DIR="$PROJECT/auth-service"
cd "$AUTH_DIR"

# Check if an existing venv has the right Python version; recreate if not.
if [[ -d ".venv" ]]; then
    VENV_VER=$(".venv/bin/python" --version 2>&1 | grep -oE '[0-9]+\.[0-9]+' | head -1)
    VENV_MAJ=$(echo "$VENV_VER" | cut -d. -f1)
    VENV_MIN=$(echo "$VENV_VER" | cut -d. -f2)
    if [[ "$VENV_MAJ" -ne 3 || "$VENV_MIN" -lt 9 ]]; then
        warn "Existing venv uses Python $VENV_VER (need 3.9+) — recreating..."
        rm -rf .venv
    else
        ok "venv exists (Python $VENV_VER)"
    fi
fi

if [[ ! -d ".venv" ]]; then
    info "Creating virtual environment..."
    "$PYTHON" -m venv .venv
    ok "venv created with $($PYTHON --version)"
fi

source .venv/bin/activate

info "Installing auth-service dependencies..."
pip install --upgrade pip --quiet
pip install -r requirements.txt --quiet
pip install asyncpg "qrcode[pil]" --quiet
ok "Auth-service dependencies installed"

info "Running Alembic migrations (SQLite)..."
alembic upgrade head
ok "Database schema ready (dev.db)"

info "Seeding first admin account (username: sysadmin, password: changeme!)..."
python seed_admin.py --username sysadmin --password "changeme!"

deactivate
cd "$PROJECT"

# =============================================================================
# 5. Backend API — venv + dependencies
# =============================================================================
header "Backend API — Python environment"

API_DIR="$PROJECT/backend-api"
cd "$API_DIR"

# Same version check as above
if [[ -d ".venv" ]]; then
    VENV_VER=$(".venv/bin/python" --version 2>&1 | grep -oE '[0-9]+\.[0-9]+' | head -1)
    VENV_MAJ=$(echo "$VENV_VER" | cut -d. -f1)
    VENV_MIN=$(echo "$VENV_VER" | cut -d. -f2)
    if [[ "$VENV_MAJ" -ne 3 || "$VENV_MIN" -lt 9 ]]; then
        warn "Existing venv uses Python $VENV_VER — recreating..."
        rm -rf .venv
    else
        ok "venv exists (Python $VENV_VER)"
    fi
fi

if [[ ! -d ".venv" ]]; then
    info "Creating virtual environment..."
    "$PYTHON" -m venv .venv
    ok "venv created with $($PYTHON --version)"
fi

source .venv/bin/activate

info "Installing backend-api dependencies..."
pip install --upgrade pip --quiet
pip install \
    "fastapi" \
    "uvicorn[standard]" \
    "httpx" \
    "pyyaml" \
    "python-jose[cryptography]" \
    "cryptography" \
    "anthropic" \
    "openai" \
    "google-genai"
ok "Backend-api dependencies installed"

deactivate
cd "$PROJECT"

# =============================================================================
# 6. Portal SPA — npm install
# =============================================================================
header "Portal SPA — Node dependencies"

SPA_DIR="$PROJECT/portal-spa"
cd "$SPA_DIR"

info "Running npm ci..."
npm ci --silent
ok "Node dependencies installed"

cd "$PROJECT"

# =============================================================================
# 7. Write the env-loader helper
# =============================================================================
# load-env.sh: source this in every new terminal before starting a service.
# It loads .env.local and additionally exports JWT_SIGNING_KEY / JWT_PUBLIC_KEY
# from the PEM files on disk so python-jose receives proper multiline PEM strings.
ENV_LOADER="$PROJECT/load-env.sh"
cat > "$ENV_LOADER" <<'LOADER'
#!/usr/bin/env bash
# Source this file to load .env.local into the current shell.
# Usage:  source ./load-env.sh   (or:  . ./load-env.sh)
_LOADER_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
_ENV="$_LOADER_DIR/.env.local"
[[ -f "$_ENV" ]] || { echo "No .env.local — run dev-setup-mac.sh first." >&2; return 1; }
set -a
# shellcheck source=/dev/null
source "$_ENV"
set +a
# Expand JWT key file paths into actual PEM content for python-jose
if [[ -n "${JWT_SIGNING_KEY_FILE:-}" && -f "$JWT_SIGNING_KEY_FILE" ]]; then
    JWT_SIGNING_KEY=$(cat "$JWT_SIGNING_KEY_FILE")
    export JWT_SIGNING_KEY
fi
if [[ -n "${JWT_PUBLIC_KEY_FILE:-}" && -f "$JWT_PUBLIC_KEY_FILE" ]]; then
    JWT_PUBLIC_KEY=$(cat "$JWT_PUBLIC_KEY_FILE")
    export JWT_PUBLIC_KEY
fi
echo "Loaded $_ENV"
LOADER
chmod +x "$ENV_LOADER"
ok "Env loader written to $ENV_LOADER"

# =============================================================================
# 8. Manual steps required
# =============================================================================
header "Manual steps required"

echo ""
manual "IMPORTANT — Change the admin password after first login:"
echo "         Seed admin: sysadmin / changeme!"
echo "         To reset:   cd $AUTH_DIR && source .venv/bin/activate"
echo "                     python seed_admin.py --username sysadmin --password '<new>'"
echo ""
manual "LLM API key (optional — needed for Log Analyser AI):"
echo "         Edit $ENV_FILE"
echo "         Set LLM_API_KEY=<your-key>  and  LLM_PROVIDER=anthropic|openai|gemini"
echo "         Or configure via Admin Console → LLM Settings after the stack is running."
echo ""
manual "Trigger scripts (Script Operations feature):"
echo "         operations.yaml currently points at ./scripts/ (relative path)."
echo "         For local dev, place test .sh scripts in:"
echo "           $PROJECT/local-data/scripts/"
echo "         Then update backend-api/config/operations.yaml 'script:' paths to:"
echo "           script: $PROJECT/local-data/scripts/<name>.sh"
echo ""
manual "Log Analyser directories:"
echo "         log_paths.local.yaml points at $PROJECT/local-data/logs/"
echo "         When using a real IDMC environment, update the paths in:"
echo "           $LOCAL_LOG_PATHS"
echo ""
manual "Enrollment base URL:"
echo "         ENROLLMENT_LINK_BASE_URL=http://localhost:5173/enroll"
echo "         Change this in $ENV_FILE when deploying to a non-localhost host."
echo ""
manual "PEM key files — keep these secret:"
echo "         $PRIV_PEM  (private key — never share)"
echo "         $PUB_PEM   (public key)"

# =============================================================================
# 9. Print the three start commands
# =============================================================================
header "Setup complete — start the stack with these three commands"

echo ""
echo -e "${BOLD}Open three terminal tabs and run one command in each:${RESET}"
echo ""
echo -e "${GREEN}── Terminal 1 — Auth Service (port 8001) ──────────────────────────────────${RESET}"
echo "  cd $AUTH_DIR"
echo "  source .venv/bin/activate"
echo "  source $ENV_LOADER"
echo "  uvicorn app.main:app --host 127.0.0.1 --port 8001 --reload"
echo ""
echo -e "${GREEN}── Terminal 2 — Backend API (port 8002) ────────────────────────────────────${RESET}"
echo "  cd $API_DIR"
echo "  source .venv/bin/activate"
echo "  source $ENV_LOADER"
echo "  uvicorn app.main:app --host 127.0.0.1 --port 8002 --reload"
echo ""
echo -e "${GREEN}── Terminal 3 — Portal SPA (port 5173, Vite dev server) ────────────────────${RESET}"
echo "  cd $SPA_DIR"
echo "  npm run dev"
echo ""
echo -e "${BOLD}Then open:${RESET}        http://localhost:5173"
echo -e "${BOLD}Admin console:${RESET}    http://localhost:5173/admin/login"
echo -e "${BOLD}Admin login:${RESET}      sysadmin / changeme!  ${YELLOW}← change this immediately${RESET}"
echo ""
echo -e "${CYAN}Tip:${RESET}  To load env vars in any new terminal tab:"
echo "  source $ENV_LOADER"
echo ""
ok "All done."
