#Requires -Version 5.1
<#
.SYNOPSIS
    Generate all required secrets for the IDMC Vendor Portal .env file.

.DESCRIPTION
    Generates cryptographically secure values for all required environment
    variables and writes them to a .env file (default: .env).
    An RS256 4096-bit RSA key pair is generated for JWT signing.

.PARAMETER OutFile
    Path to write the generated .env file. Default: .env

.PARAMETER Force
    Overwrite an existing .env file without prompting.

.EXAMPLE
    .\generate-secrets.ps1
    .\generate-secrets.ps1 -OutFile .env.staging
    .\generate-secrets.ps1 -Force
#>
[CmdletBinding()]
param (
    [string] $OutFile = ".env",
    [switch] $Force
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

function New-HexSecret([int]$Bytes = 32) {
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $buf = New-Object byte[] $Bytes
    $rng.GetBytes($buf)
    return [BitConverter]::ToString($buf).Replace("-","").ToLower()
}

function New-RsaKeyPair {
    $rsa = [System.Security.Cryptography.RSA]::Create(4096)
    $priv = "-----BEGIN RSA PRIVATE KEY-----`n" +
            [Convert]::ToBase64String($rsa.ExportRSAPrivateKey(), [Base64FormattingOptions]::InsertLineBreaks) +
            "`n-----END RSA PRIVATE KEY-----"
    $pub  = "-----BEGIN PUBLIC KEY-----`n" +
            [Convert]::ToBase64String($rsa.ExportSubjectPublicKeyInfo(), [Base64FormattingOptions]::InsertLineBreaks) +
            "`n-----END PUBLIC KEY-----"
    return @{ Private = $priv; Public = $pub }
}

# ── Guard existing file ────────────────────────────────────────────────────────
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$OutPath   = Join-Path $ScriptDir $OutFile

if (Test-Path $OutPath) {
    if (-not $Force) {
        $ans = Read-Host "$OutFile already exists. Overwrite? [y/N]"
        if ($ans -notmatch '^[Yy]') { Write-Host "Aborted."; exit 0 }
    }
}

Write-Host "Generating secrets…" -ForegroundColor Cyan

# ── Generate ───────────────────────────────────────────────────────────────────
$PgPass        = New-HexSecret 24     # 192-bit
$AdminApiKey   = New-HexSecret 32     # 256-bit
$AdminSecret   = New-HexSecret 32
$UploadSecret  = New-HexSecret 32
$KeyPair       = New-RsaKeyPair

# Inline PEM as single-line with \n for Docker env var compatibility
$PrivInline = $KeyPair.Private -replace "`r`n","`n" -replace "`n","\\n"
$PubInline  = $KeyPair.Public  -replace "`r`n","`n" -replace "`n","\\n"

# ── Write .env ─────────────────────────────────────────────────────────────────
$content = @"
# Generated by generate-secrets.ps1 on $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
# KEEP THIS FILE SECRET — never commit to source control

# ── Deployment ─────────────────────────────────────────────────────────────────
TAG=latest
PORTAL_BASE_URL=https://your-host.com

# ── Database ───────────────────────────────────────────────────────────────────
POSTGRES_USER=idmc_portal
POSTGRES_PASSWORD=$PgPass
POSTGRES_DB=idmc_portal

# ── Auth Service ───────────────────────────────────────────────────────────────
JWT_SIGNING_KEY=$PrivInline
JWT_PUBLIC_KEY=$PubInline
ADMIN_API_KEY=$AdminApiKey
ADMIN_SESSION_SECRET=$AdminSecret

# ── Backend API ────────────────────────────────────────────────────────────────
UPLOAD_TOKEN_SECRET=$UploadSecret

# ── LLM Integration (set via Admin Console after first boot) ───────────────────
LLM_PROVIDER=anthropic
LLM_API_KEY=
LLM_MODEL=claude-opus-4-8
LLM_MAX_CONTEXT_TOKENS=80000
"@

$content | Set-Content -Path $OutPath -Encoding UTF8

Write-Host ""
Write-Host "  Written: $OutPath" -ForegroundColor Green
Write-Host ""
Write-Host "  Next steps:" -ForegroundColor White
Write-Host "    1. Edit $OutFile — set PORTAL_BASE_URL and LLM_API_KEY"
Write-Host "    2. Run:  `$env:TAG='latest'; docker compose --env-file $OutFile up -d"
Write-Host "    3. Seed admin: docker compose exec auth-service python seed_admin.py"
Write-Host ""
Write-Host "  WARNING: $OutFile contains private keys. Do not commit to git." -ForegroundColor Yellow
